import { test } from 'node:test';
import assert from 'node:assert/strict';
import * as XLSX from 'xlsx';
import { parseStatementSheet } from '../src/lib/bank/sheet.js';
import { parseStatementTable } from '../src/lib/bank/statement.js';

// Excel stores a date as days since 1899-12-30.
const serial = (iso) => (Date.parse(`${iso}Z`) - Date.UTC(1899, 11, 30)) / 864e5;
const date = (iso) => ({ t: 'n', v: serial(iso), z: 'yyyy-mm-dd hh:mm:ss' });
const n1 = (v) => ({ t: 'n', v, z: '0.0' });
const n2 = (v) => ({ t: 'n', v, z: '#,##0.00' });

/** A wallet export like the ones eSewa-style apps send: filter block, table, total, status counts. */
function walletSheet({ failed = true } = {}) {
  const aoa = [
    ['Transaction Statement'],
    ['From', 'NOV 1 2026', 'To', 'NOV 1 2026'],
    ['Generated On', date('2026-11-01T22:28:48'), 'Status', 'ALL'],
    ['Channel', 'ALL', 'Dr/Cr', 'ALL'],
    ['Generated by', '9800000000'],
    [],
    [],
    ['Reference Code', 'Date Time', 'Description', 'Dr.', 'Cr.', 'Status', 'Balance (NPR)', 'Channel'],
    ['1ABCD12', date('2026-11-01T21:05:10'), 'Paid for Bagmati Khaja Ghar', n1(135), n1(0), 'COMPLETE', n2(512.4), 'App'],
    ...(failed ? [['1QRST56', date('2026-11-01T20:40:00'), 'Paid for Momo Hut', n1(450), n1(0), 'FAILED', n2(647.4), 'App']] : []),
    ['1WXYZ34', date('2026-10-31T18:12:44'), 'Fund Transfer to Bank', n1(650), n1(0), 'COMPLETE', n2(647.4), 'App'],
    ['', '', 'Total', n1(785), n1(0)],
    [],
    [],
    ['Total', 2],
    ['Pending', 0],
    ['Complete', 2],
    ['canceled', 0],
    ['Time out', 0],
  ];
  const ws = XLSX.utils.aoa_to_sheet(aoa.map((r) => r.map((c) => (c && typeof c === 'object' ? c.v : c))));
  // Put the number formats back (aoa_to_sheet takes plain values).
  aoa.forEach((r, ri) => r.forEach((c, ci) => {
    if (c && typeof c === 'object') Object.assign(ws[XLSX.utils.encode_cell({ r: ri, c: ci })], c);
  }));
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Statement');
  return wb;
}

function check(st) {
  assert.equal(st.rows.length, 2);
  const [a, b] = st.rows; // oldest first
  assert.equal(a.date, '2026-10-31');
  assert.equal(a.time, '18:12');
  assert.equal(a.debit, 650);
  assert.equal(a.credit, null);
  assert.equal(a.balance, 647.4);
  assert.equal(a.ref, '1WXYZ34');
  assert.equal(a.description, 'Fund Transfer to Bank'); // no "COMPLETE App" stuck on
  assert.equal(b.date, '2026-11-01');
  assert.equal(b.time, '21:05');
  assert.equal(b.debit, 135);
  assert.equal(b.balance, 512.4);
  assert.deepEqual(st.checks, { checked: 1, ok: 1, fixed: 0 });
}

test('wallet .xlsx: header found below the filter block, total and status counts skipped', () => {
  const data = XLSX.write(walletSheet(), { type: 'array', bookType: 'xlsx' });
  const st = parseStatementSheet(XLSX, new Uint8Array(data));
  check(st);
  assert.equal(st.source, 'spreadsheet');
  assert.match(st.warnings.join(' '), /1 failed, cancelled or pending transaction was left out/);
  assert.equal(st.account, ''); // the phone number in "Generated by" is not kept
});

test('old .xls (BIFF8) reads the same', () => {
  const data = XLSX.write(walletSheet({ failed: false }), { type: 'array', bookType: 'biff8' });
  const st = parseStatementSheet(XLSX, new Uint8Array(data));
  check(st);
  assert.equal(st.warnings.length, 0);
});

test('an HTML table saved as .xls (some banks do this) reads too', () => {
  const html = `<table>
    <tr><td>Statement of Account</td></tr><tr><td>A/C No: 01234567890123</td></tr>
    <tr><th>Txn Date</th><th>Particulars</th><th>Withdraw</th><th>Deposit</th><th>Balance</th></tr>
    <tr><td>28/10/2026</td><td>Opening Balance</td><td></td><td></td><td>5,000.00</td></tr>
    <tr><td>29/10/2026</td><td>FONEPAY/712345678/KOTHEYS</td><td>630.00</td><td></td><td>4,370.00</td></tr>
    <tr><td>30/10/2026</td><td>SALARY OCT</td><td></td><td>20,000.00</td><td>24,370.00</td></tr></table>`;
  const st = parseStatementSheet(XLSX, new TextEncoder().encode(html));
  assert.equal(st.account, '0123');
  assert.equal(st.openingBalance, 5000);
  assert.equal(st.rows.length, 2);
  assert.equal(st.rows[0].debit, 630);
  assert.equal(st.rows[1].credit, 20000);
  assert.deepEqual(st.checks, { checked: 2, ok: 2, fixed: 0 });
});

test('the sheet with the transactions is chosen when there are several', () => {
  const wb = walletSheet({ failed: false });
  const cover = XLSX.utils.aoa_to_sheet([['Customer details'], ['Name', 'Someone']]);
  XLSX.utils.book_append_sheet(wb, cover, 'Cover');
  wb.SheetNames.reverse(); // cover first
  const st = parseStatementSheet(XLSX, new Uint8Array(XLSX.write(wb, { type: 'array', bookType: 'xlsx' })));
  check(st);
});

